"""List the licences of everything the Local Catalog ships or needs at runtime (for the L4 compatibility check).

uv run python scripts/licenses.py            # Python runtime dependencies
uv run python scripts/licenses.py --markdown # the same as THIRD_PARTY_LICENSES.md (a test keeps the file current)
node scripts/licenses.mjs                    # what ends up in the web bundle (needs web/node_modules)
"""

import re
from importlib import metadata

ROOT = "resink-catalog"
# pulled in by the pyiceberg extras `sql-sqlite` and `pyarrow` (the extras are not followed automatically)
EXTRAS = ["pyarrow", "sqlalchemy", "greenlet"]


def licence(dist: metadata.Distribution) -> str:
    md = dist.metadata
    if md.get("License-Expression"):
        return md["License-Expression"]
    classifiers = [c.split("::")[-1].strip() for c in md.get_all("Classifier") or [] if c.startswith("License ::")]
    if classifiers:
        return "; ".join(classifiers)
    text = (md.get("License") or "").strip().splitlines()
    return text[0][:60] if text else "UNKNOWN"


def closure(root: str) -> dict[str, metadata.Distribution]:
    seen: dict[str, metadata.Distribution] = {}
    todo = [root, *EXTRAS]
    while todo:
        name = re.split(r"[ ;<>=!~\[(]", todo.pop().lower(), maxsplit=1)[0].replace("_", "-")
        if name in seen:
            continue
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue  # an optional extra that is not installed
        seen[name] = dist
        for req in dist.requires or []:
            if "extra ==" not in req:
                todo.append(req)
    return seen


# Installed only on some platforms or Python versions, so the running interpreter cannot list them (from uv.lock).
PLATFORM_ONLY = {
    "keyring": ("MIT", "macOS and Windows"),
    "jaraco.classes": ("MIT", "macOS and Windows"),
    "jaraco.context": ("MIT", "macOS and Windows"),
    "jaraco.functools": ("MIT", "macOS and Windows"),
    "more-itertools": ("MIT", "macOS and Windows"),
    "pywin32-ctypes": ("BSD-3-Clause", "Windows"),
    "importlib-metadata": ("Apache-2.0", "Python 3.10 and 3.11"),
    "zipp": ("MIT", "Python 3.10 and 3.11"),
    "backports.tarfile": ("MIT", "Python 3.10 and 3.11"),
}
# Licences that would not be compatible with shipping under Apache-2.0 as a package that users install.
FORBIDDEN = ("GPL", "AGPL", "SSPL", "BUSL", "Commons Clause", "UNKNOWN")


def markdown() -> str:
    deps = {n: d for n, d in closure(ROOT).items() if n != ROOT}
    out = [
        "# Third-party licences",
        "",
        "resink-catalog is Apache-2.0. These are the runtime dependencies of the Python package and the web UI it",
        "ships, with their licences. Generated by `uv run python scripts/licenses.py --markdown`; the test",
        "`tests/test_licenses.py` fails when this file or the policy below is out of date.",
        "",
        "Policy: permissive licences only (MIT, BSD, Apache-2.0, PSF, ISC, 0BSD, Zlib, CC0). `certifi` is MPL-2.0, a",
        "file-level licence that applies only to modified copies of its own files; we ship it unmodified. No GPL, AGPL,",
        "SSPL or source-available licences, in the package, the web bundle or the Docker image.",
        "",
        "## Python, all platforms",
        "",
        "| Package | Version | Licence |",
        "| --- | --- | --- |",
    ]
    out += [f"| {n} | {d.version} | {licence(d)} |" for n, d in sorted(deps.items())]
    out += [
        "",
        "## Python, only on some platforms or versions",
        "",
        "| Package | Licence | Installed on |",
        "| --- | --- | --- |",
    ]
    out += [f"| {n} | {lic} | {where} |" for n, (lic, where) in sorted(PLATFORM_ONLY.items())]
    out += [
        "",
        "## Web UI bundle (`web/`, built into the wheel)",
        "",
        "| Package | Licence |",
        "| --- | --- |",
        "| react | MIT |",
        "| react-dom | MIT |",
        "| scheduler | MIT |",
        "",
        "Development tools (Vite, Vitest, Playwright, TypeScript, pytest, ruff) are not shipped.",
        "",
    ]
    return "\n".join(out)


if __name__ == "__main__":
    import sys

    if "--markdown" in sys.argv:
        print(markdown(), end="")
    else:
        for name, dist in sorted(closure(ROOT).items()):
            print(f"{name:32} {dist.version:12} {licence(dist)}")
